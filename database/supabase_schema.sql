-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.warehouses (
    warehouse_id VARCHAR(10) PRIMARY KEY,
    warehouse_name VARCHAR(100) NOT NULL,
    rice_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    wheat_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    sugar_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
);

CREATE TABLE IF NOT EXISTS public.shops (
    shop_id VARCHAR(10) PRIMARY KEY,
    shop_name VARCHAR(120) NOT NULL,
    location_name VARCHAR(120) NOT NULL,
    rice_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    wheat_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    sugar_kg NUMERIC(10,2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.delivery_requests (
    request_id VARCHAR(20) PRIMARY KEY,
    shop_id VARCHAR(10) NOT NULL REFERENCES public.shops(shop_id),
    urgency INT NOT NULL,
    total_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    details VARCHAR(500) DEFAULT '',
    arrival_order INT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.request_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(20) NOT NULL REFERENCES public.delivery_requests(request_id) ON DELETE CASCADE,
    commodity_name VARCHAR(30) NOT NULL,
    quantity_kg NUMERIC(10,2) NOT NULL
);

-- Authentication & Role-Based Access Table
CREATE TABLE IF NOT EXISTS public.app_users (
    user_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'SHOP_DEALER', -- 'ADMIN' or 'SHOP_DEALER'
    assigned_shop_id VARCHAR(10) REFERENCES public.shops(shop_id),
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Configure Row Level Security (RLS) for public demo access
ALTER TABLE public.warehouses ENABLE ROW LEVEL SECURITY;
